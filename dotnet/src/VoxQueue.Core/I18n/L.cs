    /// A missing key returns its own name rather than an empty string, so a gap
    /// shows up on screen instead of silently producing a blank label.
    /// </summary>
    public static string Tt(string key)
    {
        if (T.TryGetValue(_code, out var map) &&
            map.TryGetValue(key, out var value) && !string.IsNullOrEmpty(value))
            return value;

        if (T.TryGetValue("en", out var en) && en.TryGetValue(key, out var fallback))
            return fallback;

        return key;
    }

    /// <summary>Every key the table knows. Used by the self-test to prove none is missing.</summary>
    public static IEnumerable<string> AllKeys =>
        T.TryGetValue("en", out var en) ? en.Keys : Enumerable.Empty<string>();

    /// <summary>Descriptive hint: Polish when the UI is Polish, English otherwise.</summary>
    public static string Hint(string key)
    {
        if (!Hints.TryGetValue(key, out var pair)) return key;
        return _code == "pl" ? pair.pl : pair.en;
    }

    public static string Defect(string code)
    {
        if (!Defects.TryGetValue(code, out var pair)) return code;
        return _code == "pl" ? pair.pl : pair.en;
    }

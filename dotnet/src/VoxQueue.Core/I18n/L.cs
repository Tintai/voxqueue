    private static string _code = "en";

    public static string Code => _code;

    public static void Set(string? code)
    {
        if (string.IsNullOrEmpty(code) || code == "system") code = Detect();
        _code = T.ContainsKey(code!) ? code! : "en";
    }

    private static string Detect()
    {
        try
        {
            var c = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
            if (c == "nn") return "nb";
            return T.ContainsKey(c) ? c : "en";
        }
        catch { return "en"; }
    }

    /// <summary>Translate a key. An unknown key returns itself, which makes gaps obvious.</summary>
    /// <summary>
    /// Resolves a key for the active language, falling back to English and then
    /// to the key itself.

class I18N:
    """Lookup with English fallback, plus system-locale detection."""

    def __init__(self, code: str = "system") -> None:
        self._code = "en"
        self.set_language(code)

    def set_language(self, code: str) -> None:
        if code in ("system", "", None):
            code = self._detect()
        self._code = code if code in _T else "en"

    @property
    def code(self) -> str:
        return self._code

    @staticmethod
    def _detect() -> str:
        try:
            loc = locale.getlocale()[0] or ""
        except Exception:
            loc = ""
        if not loc:
            loc = (locale.getdefaultlocale() or ("en",))[0] or "en"
        code = loc.split("_")[0].split("-")[0].lower()
        if code in _T:
            return code
        # Norwegian variants collapse onto one of the two supported blocks.
        if code in ("nn",):
            return "nb"
        return "en"

    def t(self, key: str, **fmt) -> str:
        """Translate. Missing keys fall back to English, then to the key."""
        s = _T.get(self._code, {}).get(key)
        if s is None:
            s = _EN.get(key, key)
        if fmt:
            try:
                return s.format(**fmt)
            except Exception:
                return s
        return s

    def hint(self, key: str, **fmt) -> str:
        """A descriptive hint — the longer sentence under a field.

        Same storage as t(): in this build hints are ordinary entries in the same
        table, so a hint missing from a language falls back to English like
        everything else. The method exists to mirror the C# API, where hints live
        in their own table, and so call sites read the same on both sides.

        It did not exist at all until now, which meant three call sites raised
        AttributeError the moment they ran — the Log tab's Clear button included.
        """
        return self.t(key, **fmt)


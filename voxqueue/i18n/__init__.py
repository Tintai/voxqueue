def defect_name(code: str, lang: str = "en") -> str:
    """Display name for a defect code. Falls back to the code itself."""
    table = _DEFECTS.get(lang) or {}
    if code in table:
        return table[code]
    return _EN.get(f"defect_{code}", code)
